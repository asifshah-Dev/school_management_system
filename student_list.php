    $(document).ready(function() {
        // Auto-focus on search input
        $('input[name="search"]').focus();
        
        // Initialize tooltips
        $('[data-toggle="tooltip"]').tooltip();
        
        // Auto-submit filters on change
        $('#class_filter, #village_filter, #status_filter').change(function() {
            $('#filterForm').submit();
        });
        
        // Status update button click handler
        $(document).on('click', '.status-update-btn', function(e) {
            e.preventDefault();
            var studentId = $(this).data('student-id');
            var studentName = $(this).data('student-name');
            var studentStatus = $(this).data('student-status');
            
            // Set values in modal
            $('#modal_student_id').val(studentId);
            $('#modal_student_name').text(studentName);
            
            // Set current status text
            var statusText = '';
            switch(parseInt(studentStatus)) {
                case 0:
                    statusText = lang.status_active;
                    break;
                case 1:
                    statusText = lang.status_leave;
                    break;
                case 2:
                    statusText = lang.status_struck_off;
                    break;
                default:
                    statusText = 'Unknown';
            }
            $('#current_status_text').text(statusText);
            
            // Check the appropriate radio button
            $('input[name="new_status"]').prop('checked', false);
            $('input[name="new_status"][value="' + studentStatus + '"]').prop('checked', true);
            
            // Show modal
            $('#statusModal').modal('show');
        });
        
        // Delete button confirmation
        $(document).on('click', '.delete-btn', function(e) {
            if (!confirm(lang.delete_confirm)) {
                e.preventDefault();
                return false;
            }
        });
        
        // Update status button confirmation
        $('#updateStatusBtn').on('click', function(e) {
            var selectedStatus = $('input[name="new_status"]:checked').val();
            if (!selectedStatus) {
                e.preventDefault();
                alert('Please select a status');
                return false;
            }
            if (!confirm(lang.status_update_confirm)) {
                e.preventDefault();
                return false;
            }
        });
        
        // Show/hide filters based on screen size
        function toggleFilters() {
            if ($(window).width() < 768) {
                $('.filter-row .col-md-3').addClass('mb-3');
            } else {
                $('.filter-row .col-md-3').removeClass('mb-3');
            }
        }
        
        // Initial call
        toggleFilters();
        
        // Call on window resize
        $(window).resize(toggleFilters);
    });
    
    // Function to select status by clicking on the option div
    function selectStatus(value) {
        $('input[name="new_status"]').prop('checked', false);
        $('input[name="new_status"][value="' + value + '"]').prop('checked', true);
    }
