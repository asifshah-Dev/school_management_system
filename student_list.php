        c.id AS class_id,
        c.title AS class_title,
        s.id AS section_id,
        s.title AS section_title
    FROM classes c
    LEFT JOIN class_sections cs ON cs.class_id = c.id
    LEFT JOIN sections s ON s.id = cs.section_id
    ORDER BY c.title, s.title
");

